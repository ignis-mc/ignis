package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// writeEntities writes src/ignis/text/entity.mojo from the entity tables of
// golang.org/x/net/html (unexported, so read from its source in the module
// cache).
func writeEntities(out string) {
	modcache := os.Getenv("GOMODCACHE")
	if modcache == "" {
		modcache = filepath.Join(os.Getenv("HOME"), "go", "pkg", "mod")
	}
	src, err := os.ReadFile(filepath.Join(modcache, "golang.org/x/net@v0.50.0/html/entity.go"))
	must(err)
	one := regexp.MustCompile(`^\s*"([^"]+)":\s*'\\[uU]([0-9A-Fa-f]+)',`)
	two := regexp.MustCompile(`^\s*"([^"]+)":\s*\{'\\[uU]([0-9A-Fa-f]+)', '\\[uU]([0-9A-Fa-f]+)'\},`)
	var b strings.Builder
	b.WriteString(`"""The named character references of ` + "`golang.org/x/net/html`" + ` v0.50.0
(` + "`entity.go`" + `), generated by ` + "`interop/ui`" + ` (` + "`go run . -entities`" + `); do not edit."""

comptime _ENTITIES = (
`)
	n := 0
	var line strings.Builder
	line.WriteString("\n")
	flush := func() {
		fmt.Fprintf(&b, "    %q\n", line.String())
		line.Reset()
	}
	for _, l := range strings.Split(string(src), "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "//") {
			continue
		}
		var entry string
		if m := two.FindStringSubmatch(l); m != nil {
			entry = m[1] + "\t" + strings.ToLower(strings.TrimLeft(m[2], "0")) + "," + strings.ToLower(strings.TrimLeft(m[3], "0")) + "\n"
		} else if m := one.FindStringSubmatch(l); m != nil {
			entry = m[1] + "\t" + strings.ToLower(strings.TrimLeft(m[2], "0")) + "\n"
		} else {
			continue
		}
		line.WriteString(entry)
		n++
		if line.Len() > 60 {
			flush()
		}
	}
	flush()
	b.WriteString(`)
"""Lines of "name<TAB>hex code points", the first line empty, so that a name
is found by searching for "\n" + name + "\t"."""


def entity_lookup(name: StringSlice) -> Optional[List[Int]]:
    """Returns the code points of a named character reference (Go ` + "`entity`" + `
    and ` + "`entity2`" + `), the name including its ";" if it has one."""
    var table = String(_ENTITIES)
    var key = String("\n") + name + "\t"
    var i = table.find(key)
    if i < 0:
        return None
    var start = i + key.byte_length()
    var end = table.find("\n", start)
    var out = List[Int]()
    var v = 0
    for b in table.as_bytes()[start:end]:
        if b == UInt8(ord(",")):
            out.append(v)
            v = 0
        elif b <= UInt8(ord("9")):
            v = v * 16 + Int(b) - 48
        else:
            v = v * 16 + Int(b) - 87
    out.append(v)
    return out^
`)
	must(os.WriteFile(out, []byte(b.String()), 0o644))
	fmt.Fprintf(os.Stderr, "%d entities\n", n)
}
